    @Test fun matchesReferenceRenders() {
        for (c in cases) {
            var hsl = HslCurves()
            for ((k, pts) in c.curves) hsl = hsl.with(k, HslCurve(pts))
            val t = hsl.tables()!!
            val tol = if (HslKind.HUE_HUE in c.curves) 0.01f else 0.002f
            for (p in c.px) {
                val rgb = floatArrayOf(p[0], p[1], p[2])
                HslCurves.apply(t, rgb)
                for (i in 0..2) assertEquals("${c.name} (${p[0]}, ${p[1]}, ${p[2]}) channel $i", p[3 + i], rgb[i], tol)
            }
        }
    }

    @Test fun neutralAndPeriodic() {
        assertEquals(null, HslCurves().tables())
        // a hue curve wraps: a point near red affects both ends of the axis alike
        val t = HslCurve(listOf(0.02f to 0.8f)).table(periodic = true)
        assertEquals(t.first(), t.last(), 1e-6f)
        assertEquals(0.8f, t.first(), 1e-6f)
        // flat between equal points, the exact height at a point
        val u = HslCurve(listOf(0.2f to 0.5f, 0.5f to 0.7f, 0.8f to 0.5f)).table(periodic = false, n = 101)
        assertEquals(0.7f, u[50], 1e-4f)
        assertEquals(0.5f, u[10], 1e-6f)
    }
